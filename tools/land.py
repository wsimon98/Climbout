"""Build land.js from Natural Earth 1:110m land (public domain).
Usage: python3 tools/land.py ne_110m_land.geojson land.js [tolerance_deg=0.15]
Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson"""
import json,sys,math
src,out=sys.argv[1],sys.argv[2]
tol=float(sys.argv[3]) if len(sys.argv)>3 else 0.15
g=json.load(open(src))
rings=[]
for f in g['features']:
    geom=f['geometry']
    polys=geom['coordinates'] if geom['type']=='MultiPolygon' else [geom['coordinates']]
    for p in polys:
        rings.append(p[0])  # outer ring only (110m land has few holes)
def dp(pts,tol):
    if len(pts)<3: return pts
    keep=[False]*len(pts);keep[0]=keep[-1]=True;stack=[(0,len(pts)-1)]
    while stack:
        a,b=stack.pop();ax,ay=pts[a];bx,by=pts[b];dx,dy=bx-ax,by-ay;L=math.hypot(dx,dy)
        best,bi=-1,-1
        for i in range(a+1,b):
            px,py=pts[i]
            d=abs(dy*px-dx*py+bx*ay-by*ax)/L if L else math.hypot(px-ax,py-ay)
            if d>best:best,bi=d,i
        if best>tol: keep[bi]=True;stack+=[(a,bi),(bi,b)]
    return [p for p,k in zip(pts,keep) if k]
total=0;parts=[]
for r in rings:
    s=dp(r,tol)
    # drop tiny islands
    xs=[p[0] for p in s];ys=[p[1] for p in s]
    if len(s)<4 or (max(xs)-min(xs))*(max(ys)-min(ys))<0.6: continue
    enc=' '.join('%g,%g'%(round(x,1),round(y,1)) for x,y in s[:-1])
    parts.append(enc);total+=len(s)
data='|'.join(parts)
head=('/* Simplified land outlines from Natural Earth 1:110m land (public domain, naturalearthdata.com).\n'
      '   Generated by tools/land.py: rings of "lon,lat" pairs separated by "|". */\n')
open(out,'w').write(head+'window.CLIMBOUT_LAND="'+data+'";\n')
print(len(rings),'rings ->',len(parts),'kept,',total,'pts,',len(data),'bytes')
